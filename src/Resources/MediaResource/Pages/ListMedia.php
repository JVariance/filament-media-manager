<?php

namespace TomatoPHP\FilamentMediaManager\Resources\MediaResource\Pages;

use Filament\Actions;
use Filament\Forms\Components\Textarea;
use Filament\Forms\Components\TextInput;
use Filament\Notifications\Notification;
use Filament\Resources\Pages\ManageRecords;
use Filament\Support\Enums\Width;
use Illuminate\Contracts\Support\Htmlable;
use Illuminate\Http\Exceptions\HttpResponseException;
use Livewire\Features\SupportFileUploads\TemporaryUploadedFile;
use TomatoPHP\FilamentMediaManager\Form\FocalPointPicker;
use TomatoPHP\FilamentMediaManager\Form\ImageEditorField;
use TomatoPHP\FilamentMediaManager\Form\VideoPosterPicker;
use TomatoPHP\FilamentMediaManager\Models\Folder;
use TomatoPHP\FilamentMediaManager\Models\Media;
use TomatoPHP\FilamentMediaManager\Resources\Actions\CreateMediaAction;
use TomatoPHP\FilamentMediaManager\Resources\Actions\CreateSubFolderAction;
use TomatoPHP\FilamentMediaManager\Resources\Actions\DeleteFolderAction;
use TomatoPHP\FilamentMediaManager\Resources\Actions\EditCurrentFolderAction;
use TomatoPHP\FilamentMediaManager\Resources\FolderResource;
use TomatoPHP\FilamentMediaManager\Resources\MediaResource;
use TomatoPHP\FilamentMediaManager\Services\FocalPoint;
use TomatoPHP\FilamentMediaManager\Services\ImageEditor;
use TomatoPHP\FilamentMediaManager\Services\VideoPoster;

class ListMedia extends ManageRecords
{
    protected static string $resource = MediaResource::class;

    public ?int $folder_id = null;

    public ?Folder $folder = null;

    public function getTitle(): string | Htmlable
    {
        return $this->folder->name;
    }

    public function getSubheading(): string | Htmlable
    {
        return $this->folder->description ?? '';
    }

    public function mount(): void
    {
        parent::mount(); // TODO: Change the autogenerated stub

        // The media list always belongs to a folder; without one, send the user to the folders list.
        if (! request()->has('folder_id')) {
            throw new HttpResponseException(
                redirect()->to(FolderResource::getUrl('index'))
            );
        }

        $folder = Folder::find(request()->input('folder_id'));
        if (! $folder) {
            abort(404, 'Folder ID is required');
        } else {
            if ($folder->is_protected && ! session()->has('folder_password')) {
                abort(403, 'You Cannot Access This Folder');
            }
        }

        $this->folder = $folder;
        $this->folder_id = request()->input('folder_id');
        session()->put('folder_id', $this->folder_id);
    }

    protected function getHeaderActions(): array
    {
        $folder_id = $this->folder_id;

        $folder = config('filament-media-manager.model.folder')::find($folder_id);

        if (filament('filament-media-manager')->allowUserAccess && (! empty($folder->user_id))) {
            if ($folder->user_id === auth()->user()->id && $folder->user_type === get_class(auth()->user())) {
                return [
                    CreateMediaAction::make($folder_id),
                    CreateSubFolderAction::make($folder_id),
                    DeleteFolderAction::make($folder_id),
                    EditCurrentFolderAction::make($folder_id),
                ];
            } else {
                return [];
            }
        } else {
            return [
                CreateMediaAction::make($folder_id),
                CreateSubFolderAction::make($folder_id),
                DeleteFolderAction::make($folder_id),
                EditCurrentFolderAction::make($folder_id),
            ];
        }
    }

    public function folderAction(?Folder $item = null)
    {
        return Actions\Action::make('folderAction')
            ->requiresConfirmation(function (array $arguments) {
                if ($arguments['record']['is_protected']) {
                    return true;
                } else {
                    return false;
                }
            })
            ->schema(function (array $arguments) {
                if ($arguments['record']['is_protected']) {
                    return [
                        TextInput::make('password')
                            ->password()
                            ->revealable()
                            ->required()
                            ->maxLength(255),
                    ];
                } else {
                    return null;
                }
            })
            ->action(function (array $arguments, array $data) {
                if ($arguments['record']['is_protected']) {
                    if ($arguments['record']['password'] != $data['password']) {
                        Notification::make()
                            ->title('Password is incorrect')
                            ->danger()
                            ->send();

                        return;
                    } else {
                        session()->put('folder_password', $data['password']);
                    }
                }
                if (! $arguments['record']['model_type']) {
                    if (filament()->getTenant()) {
                        return redirect()->to(url(filament()->getCurrentPanel()->getId() . '/' . filament()->getTenant()->id . '/media?folder_id=' . $arguments['record']['id']));
                    } else {
                        return redirect()->route('filament.' . filament()->getCurrentPanel()->getId() . '.resources.media.index', ['folder_id' => $arguments['record']['id']]);
                    }
                }
                if (! $arguments['record']['model_id'] && ! $arguments['record']['collection']) {
                    if (filament()->getTenant()) {
                        return redirect()->to(url(filament()->getCurrentPanel()->getId() . '/' . filament()->getTenant()->id . '/folders?model_type=' . $arguments['record']['model_type']));
                    } else {
                        return redirect()->route('filament.' . filament()->getCurrentPanel()->getId() . '.resources.folders.index', ['model_type' => $arguments['record']['model_type']]);
                    }
                } elseif (! $arguments['record']['model_id']) {
                    if (filament()->getTenant()) {
                        return redirect()->to(url(filament()->getCurrentPanel()->getId() . '/' . filament()->getTenant()->id . '/folders?model_type=' . $arguments['record']['model_type'] . '&collection=' . $arguments['record']['collection']));
                    } else {
                        return redirect()->route('filament.' . filament()->getCurrentPanel()->getId() . '.resources.folders.index', ['model_type' => $arguments['record']['model_type'], 'collection' => $arguments['record']['collection']]);
                    }
                } else {
                    if (filament()->getTenant()) {
                        return redirect()->to(url(filament()->getCurrentPanel()->getId() . '/' . filament()->getTenant()->id . '/media?folder_id=' . $arguments['record']['id']));
                    } else {
                        return redirect()->route('filament.' . filament()->getCurrentPanel()->getId() . '.resources.media.index', ['folder_id' => $arguments['record']['id']]);
                    }
                }
            })
            ->view('filament-media-manager::pages.folder-action', ['item' => $item]);
    }

    public function editMedia(): Actions\Action
    {
        return Actions\Action::make('editMedia')
            ->label(trans('filament-media-manager::messages.media.meta.edit-media'))
            ->icon('heroicon-s-pencil')
            ->color('primary')
            ->fillForm(function (array $arguments): array {
                $media = Media::find($arguments['record']['id']);

                return [
                    'title' => $media->getCustomProperty('title'),
                    'description' => $media->getCustomProperty('description'),
                    'alt' => $media->getCustomProperty('alt'),
                    'focal' => FocalPoint::get($media),
                ];
            })
            ->schema(fn (array $arguments): array => [
                TextInput::make('title')
                    ->label('Title')
                    ->maxLength(255),
                Textarea::make('description')
                    ->label('Description')
                    ->rows(3)
                    ->maxLength(500),
                TextInput::make('alt')
                    ->label('Alt Text')
                    ->maxLength(255),
                VideoPosterPicker::make('poster')
                    ->label(trans('filament-media-manager::messages.media.poster.label'))
                    ->media(fn (): ?Media => Media::find($arguments['record']['id'] ?? null))
                    ->visible(fn (): bool => ($media = Media::find($arguments['record']['id'] ?? null)) && VideoPoster::isVideo($media)),
                FocalPointPicker::make('focal')
                    ->label(trans('filament-media-manager::messages.media.focal.label'))
                    ->helperText(trans('filament-media-manager::messages.media.focal.help'))
                    ->media(fn (): ?Media => Media::find($arguments['record']['id'] ?? null))
                    ->visible(fn (): bool => ($media = Media::find($arguments['record']['id'] ?? null)) && FocalPoint::supports($media)),
            ])
            ->action(function (array $arguments, array $data) {
                $media = Media::find($arguments['record']['id']);

                $media->setCustomProperty('title', $data['title']);
                $media->setCustomProperty('description', $data['description']);
                $media->setCustomProperty('alt', $data['alt']);

                if (FocalPoint::supports($media)) {
                    FocalPoint::set($media, $data['focal'] ?? null);
                }

                $media->save();

                if (VideoPoster::isVideo($media)) {
                    VideoPosterPicker::save($media, $data['poster'] ?? null);
                }
            })
            ->successNotificationTitle('Media updated successfully');
    }

    /**
     * Crop, rotate and flip an image (ImageEditorField), and save it in place or as a copy
     */
    public function editImage(): Actions\Action
    {
        $media = fn (array $arguments): ?Media => Media::find($arguments['record']['id'] ?? null);

        return Actions\Action::make('editImage')
            ->label(trans('filament-media-manager::messages.media.editor.label'))
            ->icon('heroicon-s-scissors')
            ->color('gray')
            ->visible(fn (array $arguments): bool => ($image = $media($arguments)) && ImageEditor::supports($image))
            ->authorize(fn (array $arguments): bool => ($image = $media($arguments)) && static::getResource()::canEdit($image))
            ->modalHeading(fn (array $arguments): string => trans('filament-media-manager::messages.media.editor.label') . ': ' . $media($arguments)?->file_name)
            ->modalWidth(Width::SixExtraLarge)
            ->schema(fn (array $arguments): array => [
                ImageEditorField::make('image')
                    ->hiddenLabel()
                    ->media(fn (): ?Media => $media($arguments)),
            ])
            // The editor has its own buttons, which upload the image first
            ->modalSubmitAction(false)
            ->extraModalFooterActions(fn (array $arguments): array => [
                Actions\Action::make('restoreOriginal')
                    ->label(trans('filament-media-manager::messages.media.editor.restore'))
                    ->color('danger')
                    ->link()
                    ->visible(fn (): bool => ($image = $media($arguments)) && ImageEditor::hasOriginal($image))
                    ->requiresConfirmation()
                    ->modalDescription(trans('filament-media-manager::messages.media.editor.restore_confirm'))
                    ->action(function () use ($media, $arguments): void {
                        ImageEditor::restoreOriginal($media($arguments));

                        Notification::make()->title(trans('filament-media-manager::messages.media.editor.restored'))->success()->send();
                    })
                    ->cancelParentActions(),
            ])
            ->action(function (array $arguments, array $data) use ($media): void {
                $image = $media($arguments);
                $file = $data['image'] ?? null;

                if (! $image || ! $file instanceof TemporaryUploadedFile) {
                    return;
                }

                $saved = ($arguments['mode'] ?? 'replace') === 'copy'
                    ? ImageEditor::saveAsCopy($image, (string) $file->get(), trans('filament-media-manager::messages.media.editor.copy_name', ['name' => $image->name]))
                    : ImageEditor::replace($image, (string) $file->get());

                $file->delete();

                Notification::make()
                    ->title(trans($saved
                        ? (($arguments['mode'] ?? 'replace') === 'copy' ? 'filament-media-manager::messages.media.editor.copied' : 'filament-media-manager::messages.media.editor.saved')
                        : 'filament-media-manager::messages.media.editor.failed'))
                    ->status($saved ? 'success' : 'danger')
                    ->send();
            });
    }

    public function deleteMedia(): Actions\Action
    {
        return Actions\Action::make('deleteMedia')
            ->label(trans('filament-media-manager::messages.media.meta.delete-media'))
            ->icon('heroicon-s-trash')
            ->color('danger')
            ->requiresConfirmation()
            ->action(function (array $arguments) {
                $media = Media::find($arguments['record']['id']);
                $media->delete();
            })
            ->successNotificationTitle(trans('filament-media-manager::messages.media.notifications.delete-folder'));

    }
}
